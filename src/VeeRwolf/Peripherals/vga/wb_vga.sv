    input  logic        wb_rst_i,

    input  logic [11:0] wb_adr_i,
    input  logic [31:0] wb_dat_i,
    input  logic [3:0]  wb_sel_i,
    input  logic        wb_we_i,
    input  logic        wb_cyc_i,
    input  logic        wb_stb_i,

    output logic [31:0] wb_dat_o,
    output logic        wb_ack_o,

    output logic        vga_hsync,
    output logic        vga_vsync,
    output logic [3:0]  vga_red,
    output logic [3:0]  vga_green,
    output logic [3:0]  vga_blue
);

    //---------------------------------------------------------
    // Display parameters
    //---------------------------------------------------------
    localparam int ACTIVE_COLS = 640;
    localparam int ACTIVE_ROWS = 480;
    localparam int SPRITE_SIZE = 32;
    localparam int N_SPRITES   = 32;

    //---------------------------------------------------------
    // Register map  (reg_sel = wb_adr_i[11:2])
    //
    //   Word  5  0x014  REG_BG_COLOR — [11:8]=R [7:4]=G [3:0]=B
    //   Word 32+n*2  0x080+n*8  SPRITE_POS[n] — [19:10]=y_pos [9:0]=x_pos
    //   Word 33+n*2  0x084+n*8  SPRITE_CFG[n] — [31:25]=sprite_id (7-bit)
    //                                            [15:12]=R [11:8]=G [7:4]=B
    //                                            [1]=sprite_type (0=32x32, 1=16x16)
    //                                            [0]=visible
    //---------------------------------------------------------
    localparam logic [9:0] REG_BG_COLOR = 10'd5;

    logic [9:0] reg_sel;
    logic       wb_access;
    logic [4:0] spr_idx;      // sprite index, valid when is_sprite_reg
    logic       spr_is_cfg;   // 0 = POS word, 1 = CFG word
    logic       is_sprite_reg;

    assign reg_sel       = wb_adr_i[11:2];
    assign wb_access     = wb_cyc_i && wb_stb_i;
    // reg_sel[6:1] in range 16..47 for sprites 0..31; subtract 16 to get index
    assign spr_idx       = reg_sel[6:1] - 5'd16;
    assign spr_is_cfg    = reg_sel[0];
    assign is_sprite_reg = (reg_sel >= 10'd32) && (reg_sel <= 10'd95);

    //---------------------------------------------------------
    // VGA timing
    //---------------------------------------------------------
    logic        video_on;
    logic [11:0] pixel_row;
    logic [11:0] pixel_col;

    dtg u_dtg (
        .clock        (wb_clk_i),
        .rst          (wb_rst_i),
        .horiz_sync   (vga_hsync),
        .vert_sync    (vga_vsync),
        .video_on     (video_on),
        .pixel_row    (pixel_row),
        .pixel_column (pixel_col)
    );

 
    //---------------------------------------------------------
    // Sprite ROM
    //   Vivado Block Memory Generator: Single Port ROM, 32-bit x 4096,
    //   no output register (1-cycle read latency), init: guitarSprites.coe.
    //   Address layout: {sprite_id[6:0], row_offset[4:0]}
    //---------------------------------------------------------
    logic [11:0] sprite_rom_addr;
    logic [31:0] sprite_rom_data;

    sprite_rom u_sprite_rom (
        .clka  (wb_clk_i),
        .addra (sprite_rom_addr),
        .douta (sprite_rom_data)
    );

    //---------------------------------------------------------
    // CPU-visible registers
    //---------------------------------------------------------
    logic [11:0] bg_color_reg;              // [11:8]=R [7:4]=G [3:0]=B

    // Sprite descriptors (plain registers, ~512 FFs)
    logic [31:0] sprite_pos [0:N_SPRITES-1]; // [19:10]=y_pos  [9:0]=x_pos
    // [31:25]=sprite_id(7b) [15:12]=R [11:8]=G [7:4]=B [1]=sprite_type [0]=visible
    logic [31:0] sprite_cfg [0:N_SPRITES-1];

    //---------------------------------------------------------
    // Wishbone writes
    //---------------------------------------------------------
    always_ff @(posedge wb_clk_i) begin
        if (wb_rst_i) begin
            wb_ack_o     <= 1'b0;
            bg_color_reg <= 12'h000;
            for (int i = 0; i < N_SPRITES; i++) begin
                sprite_pos[i] <= 32'd0;
                sprite_cfg[i] <= 32'd0;
            end
        end else begin
            wb_ack_o <= wb_access && !wb_ack_o;

            if (wb_access && wb_we_i && !wb_ack_o) begin
                if (is_sprite_reg) begin
                    if (!spr_is_cfg)
                        sprite_pos[spr_idx] <= wb_dat_i;
                    else
                        sprite_cfg[spr_idx] <= wb_dat_i;
                end else begin
                    unique case (reg_sel)
                        REG_BG_COLOR: bg_color_reg <= wb_dat_i[11:0];
                        default: ;
                    endcase
                end
            end
        end
    end

    //---------------------------------------------------------
    // Wishbone reads
    //---------------------------------------------------------
    always_comb begin
        if (is_sprite_reg) begin
            wb_dat_o = spr_is_cfg ? sprite_cfg[spr_idx] : sprite_pos[spr_idx];
        end else begin
            unique case (reg_sel)
                REG_BG_COLOR: wb_dat_o = {20'd0, bg_color_reg};
                default:      wb_dat_o = 32'h00000000;
            endcase
        end
    end
    
