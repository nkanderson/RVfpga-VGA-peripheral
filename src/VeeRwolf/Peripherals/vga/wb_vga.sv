// Description: Wishbone VGA peripheral for 640x480 display. Implements a
//              scan-line sprite engine supporting up to 32 simultaneously
//              visible sprites using a unified Vivado BRAM ROM. Sprites may
//              be 32x32 (sprite_type=0) or 16x16 (sprite_type=1). The unified
//              sprite_rom contains both bigfont glyphs (IDs 0-94) and guitar
//              sprites (IDs 95-111) generated by gen_sprites_coe.py. A
//              scanline prefetch FSM time-multiplexes the single-port ROM
//              during H-blanking to load all 32 sprite row bitmaps. The
//              separate font_rom text overlay has been removed; all rendering
//              goes through the unified sprite engine.
// AI Contributions: Copilot (claude-sonnet-4.6) implemented the
//                   sprite engine scanline prefetch FSM, 2-layer pixel
